  // Constants and DOM references
  // ---------------------------------------------------------------------------

  const TOKEN = location.pathname.split('/')[2] || '';
  const BASE = '/s/' + TOKEN;

  const PING_INTERVAL_MS = 3000;     // server closes the session after ~10 s without pings
  const RENDER_THROTTLE_MS = 60;     // markdown re-render cadence while streaming
  const RECONNECT_DELAY_MS = 2000;   // after EventSource gives up
  const BOTTOM_THRESHOLD_PX = 48;    // "user is at the bottom" tolerance

  const $ = (id) => document.getElementById(id);
  const dom = {
    sapId: $('sap-id'),
    sysid: $('sap-sysid'),
    client: $('sap-client'),
    user: $('sap-user'),
    release: $('sap-release'),
    dotSap: $('dot-sap'),
    dotLlm: $('dot-llm'),
    statusText: $('status-text'),
    transcript: $('transcript'),
    feed: $('feed'),
    jump: $('jump'),
    input: $('input'),
    send: $('send'),
    stop: $('stop'),
    overlay: $('overlay'),
    overlayReason: $('overlay-reason'),
  };

  // Page-level state.
  const ui = {
    state: 'CREATED',          // last known session state
    closed: false,             // session_closed received or session gone
    feedback: 'all',           // whether Correct / Wrong are shown (from hello)
    initialPromptApplied: false,
    atBottom: true,            // transcript scrolled to the end
    es: null,                  // EventSource
    pingTimer: null,
    reconnectTimer: null,
    closedFallbackTimer: null,
  };

  // Transcript registries (cleared on every `hello`).
  const messages = new Map();   // assistant message id -> record
  const toolCards = new Map();  // tool call id -> record
  const codeCards = new Map();  // run_id -> record

  // ---------------------------------------------------------------------------
  // Small DOM helpers
  // ---------------------------------------------------------------------------

  /** Create an element with a class list and optional text (textContent). */
  function h(tag, className, text) {
    const el = document.createElement(tag);
    if (className) el.className = className;
    if (text !== undefined && text !== null) el.textContent = String(text);
    return el;
  }

  function button(label, className, onClick) {
    const b = h('button', 'btn ' + (className || ''), label);
    b.type = 'button';
    if (onClick) b.addEventListener('click', onClick);
    return b;
  }

  /** Thumbs up / down on an answer or a run result (the learning layers' utility signal).
   *  Nothing is rendered when the installation switched feedback off. */
  function feedbackBar(target, id) {
    if (ui.feedback === 'off') return document.createDocumentFragment();
    const bar = h('span', 'feedback');
    const up = button('Correct', 'small', () => vote('up'));
    const down = button('Wrong', 'small', () => vote('down'));
    async function vote(value) {
      up.disabled = down.disabled = true;
      try {
        const res = await post('/feedback', { target, id, value });
        if (!res.ok) { up.disabled = down.disabled = false; return; }
        bar.replaceChildren(h('span', 'tag ' + (value === 'up' ? 'ok' : 'warn'),
          value === 'up' ? 'Marked correct' : 'Marked wrong'));
      } catch (e) {
        up.disabled = down.disabled = false;
      }
    }
    bar.append(up, down);
    return bar;
  }

  function prettyJson(value) {
    if (value === undefined || value === null) return '';
    if (typeof value === 'string') return value;
    try { return JSON.stringify(value, null, 2); } catch (e) { return String(value); }
  }

  function formatMs(ms) {
    if (typeof ms !== 'number' || !isFinite(ms)) return '';
    return ms >= 1000 ? (ms / 1000).toFixed(1) + ' s' : Math.round(ms) + ' ms';
  }

  // ---------------------------------------------------------------------------
  // Optional libraries (marked, highlight.js, DOMPurify) — checked lazily so a
  // slow CDN never blocks the page. When a library arrives late, everything
  // already on screen is re-rendered once.
  // ---------------------------------------------------------------------------

  const lib = {
    get marked() {
      const m = window.marked;
      return m && typeof m.parse === 'function' ? m : null;
    },
    get hljs() {
      const hl = window.hljs;
      return hl && typeof hl.highlight === 'function' ? hl : null;
    },
    get purify() {
      const p = window.DOMPurify;
      return p && typeof p.sanitize === 'function' ? p : null;
    },
  };

  let markedConfigured = false;
  let abapRegistered = false;

  function prepareLibs() {
    if (!markedConfigured && lib.marked) {
      try { lib.marked.use({ gfm: true, breaks: false }); } catch (e) { /* older API; defaults are fine */ }
      markedConfigured = true;
    }
    if (!abapRegistered && lib.hljs) {
      try {
        if (!lib.hljs.getLanguage('abap')) lib.hljs.registerLanguage('abap', abapLanguage);
      } catch (e) { /* ignore */ }
      abapRegistered = true;
    }
  }

  /** Re-render assistant messages and code cards (called when a library loads late). */
  function rerenderAll() {
    prepareLibs();
    messages.forEach((rec) => renderMarkdownInto(rec.body, rec.text));
    codeCards.forEach((rec) => setHighlightedSource(rec.code, rec.source));
  }

  ['lib-marked', 'lib-hljs', 'lib-purify'].forEach((id) => {
    const s = $(id);
    if (s) s.addEventListener('load', rerenderAll);
  });

  /**
   * highlight.js language definition for ABAP (keyword based; enough for
   * readable report code on 4.5B and ECC 6). Registered only when highlight.js
   * has no built-in 'abap'.
   */
  function abapLanguage(hljs) {
    const KEYWORDS =
      'report program include data types type like value constants statics ' +
      'field-symbols assign unassign parameters select-options tables ranges ' +
      'select from into where up to rows order by group by having inner join ' +
      'left outer on for all entries in and or not between like as distinct ' +
      'single endselect appending corresponding fields of table package size ' +
      'loop at endloop read table with key binary search transporting no fields ' +
      'index sort by ascending descending delete adjacent duplicates comparing ' +
      'append insert modify collect clear refresh free move move-corresponding ' +
      'write skip uline new-line new-page format color intensified inverse ' +
      'hotspot reset under at position no-gap left-justified right-justified ' +
      'centered if elseif else endif case when others endcase do enddo times ' +
      'while endwhile exit continue check return stop leave to list-processing ' +
      'perform form endform using changing raising exceptions call function ' +
      'exporting importing exception exception-table destination method methods ' +
      'endmethod class endclass definition implementation public private ' +
      'protected section create object final inheriting concatenate separated ' +
      'split condense translate shift replace search find describe field lines ' +
      'occurs header line initial is bound assigned supplied requested try catch ' +
      'cleanup endtry raise message with display start-of-selection ' +
      'end-of-selection initialization at selection-screen top-of-page ' +
      'end-of-page get set submit authority-check object id begin of end of ' +
      'structure add subtract multiply divide compute string xstring length ' +
      'decimals char mode work area into table upper lower first last new ' +
      'end-of-file open dataset close dataset transfer commit rollback ' +
      'function-pool type-pools type-pool local no-display ' +
      'default obligatory lower case as checkbox radiobutton group ' +
      'selection-screen block frame title text no standard page heading ' +
      'line-size line-count no-extension no-intervals';

    return {
      name: 'ABAP',
      case_insensitive: true,
      keywords: {
        $pattern: /[\w-]+/,
        keyword: KEYWORDS,
        literal: 'space abap_true abap_false abap_undefined sy-subrc sy-tabix sy-index sy-dbcnt ' +
                 'sy-datum sy-uzeit sy-uname sy-mandt sy-langu sy-repid sy-cprog sy-tcode ' +
                 'sy-sysid sy-host sy-msgid sy-msgty sy-msgno sy-msgv1 sy-msgv2 sy-msgv3 sy-msgv4 ' +
                 'sy-linsz sy-linno sy-pagno sy-tfill sy-datlo sy-timlo sy-zonlo sy-fdpos',
        built_in: 'abs sign ceil floor trunc frac strlen xstrlen lines charlen numofchar ' +
                  'condense translate to_upper to_lower boolc xsdbool concat_lines_of ' +
                  'substring shift_left shift_right repeat reverse',
      },
      contains: [
        // full-line comment: '*' in column 1
        { className: 'comment', begin: /^\*/, end: /$/ },
        // inline comment: " to end of line
        { className: 'comment', begin: /"/, end: /$/ },
        // character literal with '' escape
        { className: 'string', begin: /'/, end: /'/, contains: [{ begin: /''/ }] },
        // string literal (7.0+) with `` escape
        { className: 'string', begin: /`/, end: /`/, contains: [{ begin: /``/ }] },
        // string template (7.40)
        { className: 'string', begin: /\|/, end: /\|/ },
        { className: 'number', begin: /\b\d+(\.\d+)?\b/, relevance: 0 },
        // field-symbols
        { className: 'symbol', begin: /<[A-Za-z_]\w*>/ },
        // host variables in new Open SQL
        { className: 'variable', begin: /@[A-Za-z_]\w*/ },
      ],
    };
  }

  // ---------------------------------------------------------------------------
  // Markdown rendering and sanitizing
  // ---------------------------------------------------------------------------

  // Allowed tags and, per tag, the attributes that survive sanitizing.
  const ALLOWED_TAGS = {
    p: [], br: [], strong: [], em: [], b: [], i: [], u: [], s: [], del: [], sub: [], sup: [], kbd: [],
    code: ['class'], pre: [],
    ul: [], ol: ['start'], li: [],
    blockquote: [], hr: [],
    h1: [], h2: [], h3: [], h4: [], h5: [], h6: [],
    a: ['href', 'title'],
    table: [], thead: [], tbody: [], tr: [], th: ['align'], td: ['align'],
  };
  // Elements whose whole subtree is dropped (everything else unknown is unwrapped).
  const DROPPED_TAGS = new Set([
    'script', 'style', 'iframe', 'frame', 'object', 'embed', 'applet', 'svg', 'math',
    'template', 'link', 'meta', 'base', 'form', 'input', 'button', 'textarea', 'select',
    'option', 'video', 'audio', 'source', 'track', 'canvas', 'noscript', 'head', 'title',
  ]);

  function attributeAllowed(tag, name, value) {
    switch (name) {
      case 'href': return /^\s*(https?:|mailto:)/i.test(value) && !/[\x00-\x1f\x7f]/.test(value);
      case 'class': return tag === 'code' && /^language-[\w+#.-]+$/.test(value);
      case 'start': return /^\d{1,6}$/.test(value);
      case 'align': return /^(left|center|right)$/i.test(value);
      case 'title': return value.length < 400;
      default: return false;
    }
  }

  /** Copy allowed nodes from `source` into `target`, building fresh elements. */
  function cleanInto(source, target) {
    source.childNodes.forEach((child) => {
      if (child.nodeType === Node.TEXT_NODE) {
        target.appendChild(document.createTextNode(child.data));
        return;
      }
      if (child.nodeType !== Node.ELEMENT_NODE) return;
      const tag = child.localName;
      if (DROPPED_TAGS.has(tag)) return;
      if (tag === 'img') {                       // images are not fetched; keep the alt text
        const alt = child.getAttribute('alt');
        if (alt) target.appendChild(document.createTextNode('[' + alt + ']'));
        return;
      }
      const attrs = ALLOWED_TAGS[tag];
      if (!attrs) {                              // unknown element: unwrap
        cleanInto(child, target);
        return;
      }
      const el = document.createElement(tag);
      attrs.forEach((name) => {
        if (!child.hasAttribute(name)) return;
        const value = child.getAttribute(name);
        if (attributeAllowed(tag, name, value)) el.setAttribute(name, value);
      });
      if (tag === 'a') {                         // never navigate the --app window away
        el.setAttribute('target', '_blank');
        el.setAttribute('rel', 'noopener noreferrer');
      }
      cleanInto(child, el);
      target.appendChild(el);
    });
  }

  /** HTML string -> sanitized DocumentFragment. */
  function sanitizeToFragment(html) {
    let input = html;
    const purify = lib.purify;
    if (purify) {
      try {
        input = purify.sanitize(html, {
          ALLOWED_TAGS: Object.keys(ALLOWED_TAGS),
          ALLOWED_ATTR: ['href', 'title', 'class', 'start', 'align'],
          ALLOW_DATA_ATTR: false,
        });
      } catch (e) { input = html; }
    }
    // A <template> parses into an inert document: nothing runs or loads.
    const tpl = document.createElement('template');
    tpl.innerHTML = input;
    const frag = document.createDocumentFragment();
    cleanInto(tpl.content, frag);
    return frag;
  }

  /** Highlight `source` as `lang` -> HTML string, or null when not possible. */
  function highlightHtml(source, lang) {
    const hl = lib.hljs;
    if (!hl || !lang) return null;
    const name = lang.toLowerCase();
    try {
      if (!hl.getLanguage(name)) return null;
      return hl.highlight(source, { language: name, ignoreIllegals: true }).value;
    } catch (e) {
      return null;
    }
  }

  /** Post-process rendered markdown: highlight fenced code, add copy buttons. */
  function decorateCodeBlocks(root) {
    root.querySelectorAll('pre > code').forEach((code) => {
      const pre = code.parentElement;
      const m = /language-([\w+#.-]+)/.exec(code.className || '');
      const lang = m ? m[1].toLowerCase() : '';
      pre.classList.add('code-block');
      if (lang) pre.dataset.lang = lang;
      const html = highlightHtml(code.textContent, lang);
      if (html !== null) {
        code.innerHTML = html;                   // hljs output from escaped text
        code.classList.add('hljs');
      }
      const src = code.textContent;
      pre.appendChild(button('Copy', 'small code-copy', (ev) => copyText(src, ev.currentTarget)));
    });
  }

  /** Render markdown text into `container` (replacing its content). */
  function renderMarkdownInto(container, text) {
    prepareLibs();
    container.replaceChildren();
    const md = lib.marked;
    if (!md) {                                   // CDN unreachable: plain, escaped text
      container.appendChild(h('div', 'md-plain', text));
      return;
    }
    let html;
    try {
      html = md.parse(text || '', { async: false });
      if (typeof html !== 'string') throw new Error('marked returned a promise');
    } catch (e) {
      container.appendChild(h('div', 'md-plain', text));
      return;
    }
    container.appendChild(sanitizeToFragment(html));
    decorateCodeBlocks(container);
  }

  /** Put ABAP source into a <code> element, highlighted when possible. */
  function setHighlightedSource(code, source) {
    prepareLibs();
    const html = highlightHtml(source, 'abap');
    if (html !== null) {
      code.innerHTML = html;
      code.classList.add('hljs');
    } else {
      code.textContent = source;
    }
  }

  // ---------------------------------------------------------------------------
  // Clipboard
  // ---------------------------------------------------------------------------

  async function copyText(text, btn) {
    let ok = false;
    try {
      if (navigator.clipboard && window.isSecureContext) {
        await navigator.clipboard.writeText(text);
        ok = true;
      }
    } catch (e) { ok = false; }
    if (!ok) {                                   // http:// on a non-localhost host
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.setAttribute('readonly', '');
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      try { ok = document.execCommand('copy'); } catch (e) { ok = false; }
      ta.remove();
    }
    if (btn) {
      const label = btn.textContent;
      btn.textContent = ok ? 'Copied' : 'Copy failed';
      setTimeout(() => { btn.textContent = label; }, 1500);
    }
  }

  // ---------------------------------------------------------------------------
  // Transcript container, auto-scroll
  // ---------------------------------------------------------------------------

  function updateAtBottom() {
    const t = dom.transcript;
    ui.atBottom = t.scrollHeight - t.scrollTop - t.clientHeight < BOTTOM_THRESHOLD_PX;
    if (ui.atBottom) dom.jump.hidden = true;
  }

  function scrollToBottom() {
    dom.transcript.scrollTop = dom.transcript.scrollHeight;
    ui.atBottom = true;
    dom.jump.hidden = true;
  }

  /** Keep the view pinned to the end when the user was already there. */
  function stickToBottom() {
    if (ui.atBottom) {
      dom.transcript.scrollTop = dom.transcript.scrollHeight;
    } else {
      dom.jump.hidden = false;
    }
  }

  function appendToFeed(el) {
    dom.feed.appendChild(el);
    stickToBottom();
  }

  function resetTranscript() {
    messages.forEach((rec) => { if (rec.timer) clearTimeout(rec.timer); });
    messages.clear();
    toolCards.clear();
    codeCards.clear();
    dom.feed.replaceChildren();
    ui.atBottom = true;
    dom.jump.hidden = true;
  }

  dom.transcript.addEventListener('scroll', updateAtBottom, { passive: true });
  dom.jump.addEventListener('click', scrollToBottom);

  // ---------------------------------------------------------------------------
  // Status, state and controls
  // ---------------------------------------------------------------------------

  const DEFAULT_STATE_TEXT = {
    CREATED: 'Starting…',
    IDLE: 'Ready',
    THINKING: 'Thinking…',
    TOOL: 'Calling SAP…',
    CHECKING: 'Checking generated code…',
    CONFIRM: 'Waiting for your confirmation',
    RUNNING: 'Running in SAP…',
    CLOSED: 'Session closed',
  };

  function setStatusText(text) {
    dom.statusText.textContent = text || '';
    dom.statusText.title = text || '';
  }

  function isBusy(state) {
    return state === 'THINKING' || state === 'TOOL' || state === 'CHECKING';
  }

  /** Enable/disable composer controls from the current state. */
  function refreshControls() {
    const s = ui.state;
    const busy = isBusy(s);
    dom.send.disabled = ui.closed || !(s === 'IDLE' || s === 'CONFIRM');
    // Stop also while a program runs in SAP: Curie aborts the job.
    dom.stop.hidden = !(busy || s === 'RUNNING') || ui.closed;
    dom.stop.disabled = ui.closed;
    dom.input.disabled = ui.closed;
    dom.dotSap.className = 'dot ' + (ui.closed || s === 'CLOSED' ? 'off' : 'on');
    dom.dotLlm.className = 'dot ' + (busy && !ui.closed ? 'active' : '');
    dom.statusText.classList.toggle('busy', (busy || s === 'RUNNING') && !ui.closed);
  }

  function setState(state, text) {
    ui.state = state || ui.state;
    setStatusText(text || DEFAULT_STATE_TEXT[ui.state] || ui.state);
    refreshControls();
    if (ui.state === 'CLOSED' && !ui.closed && !ui.closedFallbackTimer) {
      // session_closed normally follows; show a generic overlay if it does not.
      ui.closedFallbackTimer = setTimeout(() => showClosed('closed'), 1500);
    }
  }

  // ---------------------------------------------------------------------------
  // Session end
  // ---------------------------------------------------------------------------

  const REASON_TEXT = {
    browser_gone: 'Curie lost contact with this browser window (no liveness pings were received).',
    sap_gone: 'The SAP session stopped sending heartbeats. SAP GUI was closed or the connection dropped.',
    sap_closed: 'The session was closed from the SAP side.',
    idle: 'The session was closed because it was idle for too long.',
    shutdown: 'Curie is shutting down.',
    attach_timeout: 'The browser did not attach to the session in time.',
    session_gone: 'The session no longer exists on the server. It may have timed out or Curie was restarted.',
    closed: 'The session has been closed.',
    no_token: 'This page was opened without a session token in the URL.',
  };

  function showClosed(reason) {
    if (ui.closed) {
      // already closed: a later, more specific reason may still refine the text
      if (reason && reason !== 'closed') dom.overlayReason.textContent = REASON_TEXT[reason] || ('Reason: ' + reason);
      return;
    }
    ui.closed = true;
    ui.state = 'CLOSED';
    if (ui.closedFallbackTimer) { clearTimeout(ui.closedFallbackTimer); ui.closedFallbackTimer = null; }
    stopPing();
    if (ui.reconnectTimer) { clearTimeout(ui.reconnectTimer); ui.reconnectTimer = null; }
    if (ui.es) { ui.es.close(); ui.es = null; }
    // finish any streaming message visually
    messages.forEach((rec) => { if (!rec.done) rec.el.classList.remove('streaming'); });
    dom.overlayReason.textContent = REASON_TEXT[reason] || ('Reason: ' + reason);
    dom.overlay.hidden = false;
    setStatusText('Session ended');
    refreshControls();
    document.title = 'Curie — session ended';
  }

  /** Called on 404/410 from any endpoint. */
  function sessionGone() {
    showClosed('session_gone');
  }

  // ---------------------------------------------------------------------------
  // HTTP helpers
  // ---------------------------------------------------------------------------

  async function post(path, body) {
    const init = { method: 'POST', cache: 'no-store' };
    if (body !== undefined) {
      init.headers = { 'Content-Type': 'application/json' };
      init.body = JSON.stringify(body);
    }
    const res = await fetch(BASE + path, init);
    if (res.status === 404 || res.status === 410) sessionGone();
    return res;
  }

  function startPing() {
    stopPing();
    ui.pingTimer = setInterval(async () => {
      if (ui.closed) return;
      try { await post('/ping'); } catch (e) { /* transient network error; SSE state tells more */ }
    }, PING_INTERVAL_MS);
  }

  function stopPing() {
    if (ui.pingTimer) { clearInterval(ui.pingTimer); ui.pingTimer = null; }
  }

  // ---------------------------------------------------------------------------
  // Transcript items: user / assistant messages
  // ---------------------------------------------------------------------------

  function addUserMessage(d) {
    const el = h('article', 'msg user', d.text || '');
    if (d.id) el.dataset.id = d.id;
    appendToFeed(el);
  }

  function ensureAssistant(id) {
    let rec = messages.get(id);
    if (rec) return rec;
    const el = h('article', 'msg assistant streaming');
    el.dataset.id = id;
    const body = h('div', 'md');
    const foot = h('div', 'msg-foot');
    el.append(body, foot);
    rec = { id, el, body, foot, text: '', timer: null, done: false };
    messages.set(id, rec);
    appendToFeed(el);
    return rec;
  }

  function scheduleRender(rec) {
    if (rec.timer) return;
    rec.timer = setTimeout(() => {
      rec.timer = null;
      renderMarkdownInto(rec.body, rec.text);
      stickToBottom();
    }, RENDER_THROTTLE_MS);
  }

  function onAssistantStart(d) {
    ensureAssistant(d.id);
  }

  function onAssistantDelta(d) {
    const rec = ensureAssistant(d.id);
    if (rec.done) return;
    rec.text += d.text || '';
    scheduleRender(rec);
  }

  function onAssistantDone(d) {
    const rec = ensureAssistant(d.id);
    if (rec.timer) { clearTimeout(rec.timer); rec.timer = null; }
    if (typeof d.text === 'string') rec.text = d.text;
    rec.done = true;
    rec.el.classList.remove('streaming');
    renderMarkdownInto(rec.body, rec.text);
    rec.foot.replaceChildren();
    if (d.interrupted) rec.foot.appendChild(h('span', 'tag warn', 'stopped'));
    else if (d.truncated) rec.foot.appendChild(h('span', 'tag warn', 'cut at the token limit, asking again'));
    else if (rec.text.trim()) rec.foot.appendChild(feedbackBar('answer', d.id));
    stickToBottom();
  }

  // ---------------------------------------------------------------------------
  // Tool call cards
  // ---------------------------------------------------------------------------

  /** "read_table" + {table: "MARA"} -> "Read table MARA…" */
  function toolLabel(name, args) {
    let label = String(name || 'tool').replace(/[_-]+/g, ' ').trim();
    label = label.charAt(0).toUpperCase() + label.slice(1);
    const parts = [];
    if (args && typeof args === 'object') {
      Object.keys(args).forEach((k) => {
        const v = args[k];
        if (parts.length < 2 && typeof v === 'string') {
          const s = String(v).trim();
          if (s) parts.push(s.length > 48 ? s.slice(0, 45) + '…' : s);
        }
      });
    }
    return parts.length ? label + ' ' + parts.join(' · ') + '…' : label + '…';
  }

  function labelled(text, node) {
    const wrap = h('div');
    wrap.appendChild(h('div', 'label', text));
    wrap.appendChild(node);
    return wrap;
  }

  function onToolCall(d) {
    const card = h('details', 'tool');
    card.dataset.id = d.id;
    const summary = h('summary', 'tool-summary');
    const icon = h('span', 'icon spinner');
    const label = h('span', 'tool-label', toolLabel(d.name, d.args));
    label.title = d.name || '';
    const meta = h('span', 'tool-meta', 'running…');
    summary.append(icon, label, meta);

    const body = h('div', 'tool-body');
    const argsPre = h('pre', 'tool-args', prettyJson(d.args));
    body.appendChild(labelled('Arguments', argsPre));
    const resultWrap = labelled('Result', h('pre', 'tool-result'));
    resultWrap.hidden = true;
    body.appendChild(resultWrap);

    card.append(summary, body);
    toolCards.set(d.id, { card, icon, label, meta, resultWrap, resultPre: resultWrap.lastChild });
    appendToFeed(card);
  }

  function onToolResult(d) {
    let rec = toolCards.get(d.id);
    if (!rec) {                                   // result without a call (should not happen)
      onToolCall({ id: d.id, name: d.name, args: null });
      rec = toolCards.get(d.id);
    }
    const ok = !!d.ok;
    rec.icon.className = 'icon ' + (ok ? 'ok' : 'err');
    rec.meta.className = 'tool-meta ' + (ok ? 'ok' : 'err');
    rec.meta.textContent = (ok ? 'ok' : 'error') + (d.ms !== undefined ? ' · ' + formatMs(d.ms) : '');
    rec.resultPre.textContent = d.summary || (ok ? '(no output)' : '(no details)');
    rec.resultWrap.hidden = false;
    if (!ok) rec.card.open = true;
    stickToBottom();
  }

