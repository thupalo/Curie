  function addNotice(level, text) {
    const lvl = level === 'warn' || level === 'error' ? level : 'info';
    appendToFeed(h('div', 'notice ' + lvl, text || ''));
  }

  function onNotice(d) {
    addNotice(d.level, d.text);
  }

  function onSyntaxError(d) {
    const where = 'line ' + (d.line !== undefined && d.line !== null ? d.line : '?') +
                  (d.word ? ' (' + d.word + ')' : '');
    let text = 'Syntax error at ' + where + ': ' + (d.message || 'unknown error');
    if (d.attempt !== undefined && d.max_attempts !== undefined) {
      text += ' — asking the model to fix (attempt ' + d.attempt + '/' + d.max_attempts + ')';
    } else {
      text += ' — asking the model to fix';
    }
    addNotice('warn', text);
    // mark the line on the most recent code card if the run is known
    const rec = d.run_id ? codeCards.get(d.run_id) : null;
    if (rec) markErrorLine(rec, d.line, d.message);
  }

  // ---------------------------------------------------------------------------
  // Code cards (generated ABAP, audit, run, list output)
  // ---------------------------------------------------------------------------

  function badge(text, level) {
    return h('span', 'badge ' + (level || ''), text);
  }

  function riskLevel(risk) {
    switch (String(risk || '').toLowerCase()) {
      case 'low': return 'ok';
      case 'medium': return 'warn';
      case 'high': return 'err';
      default: return '';
    }
  }

  function markErrorLine(rec, line, message) {
    const n = parseInt(line, 10);
    if (!n || n < 1) return;
    const span = rec.gutter.children[n - 1];
    if (!span) return;
    span.classList.add('is-error');
    if (message) span.title = message;
  }

  function setRunStatus(rec, level, text, spinning) {
    rec.status.hidden = false;
    rec.status.className = 'run-status ' + (level || '');
    rec.status.replaceChildren();
    if (spinning) rec.status.appendChild(h('span', 'icon spinner'));
    else if (level === 'ok' || level === 'err') rec.status.appendChild(h('span', 'icon ' + level));
    rec.status.appendChild(h('span', '', text));
  }

  function disableRunButtons(rec) {
    if (rec.btnRun) rec.btnRun.disabled = true;
    if (rec.btnDiscard) rec.btnDiscard.disabled = true;
  }

  function onCodeReady(d) {
    const source = typeof d.source === 'string' ? d.source : '';
    // syntax === null means the SAP check did not run (static rules or an
    // infrastructure problem stopped the flow before it).
    const checked = !!d.syntax;
    const syntax = d.syntax || {};
    const syntaxFailed = checked && !syntax.ok;
    const audit = d.audit || null;
    const canRun = !!d.can_run;

    const card = h('section', 'code-card');
    card.dataset.runId = d.run_id;

    // header: title + badges
    const head = h('div', 'code-head');
    const origin = d.origin && d.origin.catalogue ? d.origin : null;
    const title = h('div', 'code-title', origin ? 'Catalogued report ' : 'Generated ABAP ');
    if (d.progname) title.appendChild(h('span', 'mono', d.progname));
    const badges = h('div', 'badges');
    if (origin) badges.appendChild(badge('Report catalogue', 'ok'));
    if (!checked) badges.appendChild(badge('Syntax: not checked', ''));
    else badges.appendChild(badge(syntax.ok ? 'Syntax OK' : 'Syntax error', syntax.ok ? 'ok' : 'err'));
    if (audit) {
      const level = audit.allowed ? riskLevel(audit.risk) : 'err';
      const risk = audit.risk ? ' · risk ' + String(audit.risk).toLowerCase() : '';
      badges.appendChild(badge((audit.allowed ? 'Audit: allowed' : 'Audit: blocked') + risk, level));
    } else {
      badges.appendChild(badge('Audit: not available', ''));
    }
    head.append(title, badges);

    // source with gutter and ruler
    const src = h('div', 'code-src');
    const gutter = h('div', 'code-gutter');
    const lineCount = source ? source.split('\n').length : 0;
    for (let i = 1; i <= lineCount; i++) gutter.appendChild(h('span', '', i));
    const pre = h('pre', 'code-pre');
    const code = h('code', 'language-abap');
    pre.appendChild(code);
    src.append(gutter, pre);

    // notes: syntax message, audit summary and violations
    const notes = h('div', 'code-notes');
    if (syntaxFailed) {
      const note = h('div', 'code-note err');
      const where = (syntax.line ? 'Line ' + syntax.line : 'Syntax') + (syntax.word ? ', word ' + syntax.word : '');
      note.appendChild(h('span', 'title', where + ': '));
      note.appendChild(document.createTextNode(syntax.message || 'syntax check failed'));
      notes.appendChild(note);
    }
    if (audit) {
      const note = h('div', 'code-note ' + (audit.allowed ? riskLevel(audit.risk) : 'err'));
      note.appendChild(h('span', 'title', 'Audit: '));
      note.appendChild(document.createTextNode(audit.summary || (audit.allowed ? 'no objections' : 'blocked')));
      const violations = Array.isArray(audit.violations) ? audit.violations : [];
      if (violations.length) {
        const ul = h('ul');
        violations.forEach((v) => ul.appendChild(h('li', '', String(v))));
        note.appendChild(ul);
      }
      notes.appendChild(note);
    }
    if (!notes.childElementCount) notes.hidden = true;

    // actions
    const actions = h('div', 'code-actions');
    const rec = {
      runId: d.run_id, card, code, gutter, source,
      status: h('div', 'run-status'), output: null, btnRun: null, btnDiscard: null,
    };
    rec.status.hidden = true;

    if (canRun) {
      rec.btnRun = button('Run in SAP', 'primary', async () => {
        disableRunButtons(rec);
        setRunStatus(rec, '', 'Starting…', true);
        try {
          const res = await post('/runs/' + encodeURIComponent(d.run_id) + '/confirm');
          if (!res.ok && res.status !== 404 && res.status !== 410) {
            setRunStatus(rec, 'err', 'Could not start the run (HTTP ' + res.status + ')');
          }
        } catch (e) {
          setRunStatus(rec, 'err', 'Could not reach Curie: ' + e.message);
        }
      });
      actions.appendChild(rec.btnRun);
    }
    rec.btnDiscard = button('Discard', '', async () => {
      disableRunButtons(rec);
      try {
        const res = await post('/runs/' + encodeURIComponent(d.run_id) + '/discard');
        if (res.ok) setRunStatus(rec, '', 'Discarded');
        else if (res.status !== 404 && res.status !== 410) setRunStatus(rec, 'err', 'Could not discard (HTTP ' + res.status + ')');
      } catch (e) {
        setRunStatus(rec, 'err', 'Could not reach Curie: ' + e.message);
      }
    });
    actions.appendChild(rec.btnDiscard);
    if (!canRun) {
      let why;
      if (audit && !audit.allowed) why = checked ? 'blocked by audit' : 'rejected by static rules';
      else if (!checked) why = 'not checked in SAP';
      else if (!syntax.ok) why = 'syntax check failed';
      else why = 'not runnable';
      actions.appendChild(h('span', 'hint', 'Cannot run: ' + why));
    }

    card.append(head, src, notes, actions, rec.status);
    codeCards.set(d.run_id, rec);
    setHighlightedSource(code, source);
    if (syntaxFailed) markErrorLine(rec, syntax.line, syntax.message);
    appendToFeed(card);
  }

  /** Find the card for a run, creating a stub when events arrive out of order. */
  function cardFor(runId) {
    let rec = codeCards.get(runId);
    if (!rec) {
      onCodeReady({ run_id: runId, progname: '', source: '', syntax: { ok: true }, audit: null, can_run: false });
      rec = codeCards.get(runId);
    }
    return rec;
  }

  function onRunStarted(d) {
    const rec = cardFor(d.run_id);
    disableRunButtons(rec);
    const sync = String(d.mode || '').toUpperCase() === 'S' || !d.job;
    setRunStatus(rec, '', sync ? 'Running synchronously' : 'Running as job ' + d.job, true);
    stickToBottom();
  }

  function onRunResult(d) {
    const rec = cardFor(d.run_id);
    disableRunButtons(rec);
    const ok = !!d.ok;
    const rc = d.rc !== undefined && d.rc !== null ? ' · rc ' + d.rc : '';
    if (ok) {
      setRunStatus(rec, 'ok', 'Finished' + rc + (d.message ? ' — ' + d.message : ''));
    } else {
      setRunStatus(rec, 'err', 'Failed' + rc + (d.message ? ' — ' + d.message : ''));
    }

    const lines = Array.isArray(d.lines) ? d.lines.map((l) => String(l)) : [];
    if (rec.output) rec.output.remove();
    const out = h('div', 'run-output');
    const bar = h('div', 'run-output-bar');
    bar.appendChild(h('span', '', 'SAP list output · ' + lines.length + (lines.length === 1 ? ' line' : ' lines')));
    const text = lines.join('\n');
    bar.appendChild(button('Copy', 'small', (ev) => copyText(text, ev.currentTarget)));
    if (ok) bar.appendChild(feedbackBar('run', d.run_id));
    const pre = h('pre', '', lines.length ? text : '(no output)');
    out.append(bar, pre);
    rec.output = out;
    rec.card.appendChild(out);
    stickToBottom();
  }

  // ---------------------------------------------------------------------------
  // Composer
