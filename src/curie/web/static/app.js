  function autosize() {
    const ta = dom.input;
    ta.style.height = 'auto';
    ta.style.height = Math.min(ta.scrollHeight + 2, 160) + 'px';
  }

  async function sendPrompt() {
    const text = dom.input.value.trim();
    if (!text || dom.send.disabled || ui.closed) return;
    dom.send.disabled = true;
    try {
      const res = await post('/prompt', { text });
      if (res.status === 202 || res.ok) {
        dom.input.value = '';
        autosize();
      } else if (res.status === 409) {
        addNotice('warn', 'A turn is already running. Wait for it to finish or press Stop.');
      } else if (res.status !== 404 && res.status !== 410) {
        addNotice('error', 'Could not send the prompt (HTTP ' + res.status + ').');
      }
    } catch (e) {
      addNotice('error', 'Could not reach Curie: ' + e.message);
    } finally {
      refreshControls();
      dom.input.focus();
    }
  }

  async function stopTurn() {
    if (ui.closed) return;
    dom.stop.disabled = true;
    try {
      await post('/stop');
    } catch (e) {
      addNotice('error', 'Could not reach Curie: ' + e.message);
    } finally {
      refreshControls();
    }
  }

  dom.send.addEventListener('click', sendPrompt);
  dom.stop.addEventListener('click', stopTurn);
  dom.input.addEventListener('input', autosize);
  dom.input.addEventListener('keydown', (ev) => {
    if (ev.key === 'Enter' && !ev.shiftKey && !ev.isComposing) {
      ev.preventDefault();
      sendPrompt();
    } else if (ev.key === 'Escape' && !dom.stop.hidden) {
      stopTurn();
    }
  });

